name = "Moses"
age = 34
student = False
print("My name is " + name + ", I am " + str(age) + " years old, and student status is " + str(student) + ".") #hard to read- there are a lot of plus signs and you have to worry about spaces and types.

print(f"My name is {name}, I am {age} years old, and student status is {student}.") #shorter, cleaner and easier to read.

print (f"2 + 3 = {2+3}") #you can also add expressions

