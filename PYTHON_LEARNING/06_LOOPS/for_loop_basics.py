#FOR LOOP - go through a group of items one by one to do something for each item

for i in (1,2,3,4,5):
    print(f"Round:{i}")

print()

#use the same word: variable=singular, sequence = plural

items = (1,2,3,4,5)
for item in items:
    print(f"Round: {item}")

print()

names = ("Moses", "Mercy", "Imani")
for name in names:
    print(f"Name: {name}")