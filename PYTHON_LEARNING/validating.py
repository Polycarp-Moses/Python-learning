#Validating

#isalpha() -str method that checks if the string has only letters. Output is boolean

country = "Kenya"
print(country.isalpha())
name = "Moses1"
print(name.isalpha())

#isnumeric () -str method that checks if the string has only numbers. Output also boolean

phone = "0705097054"
print(phone.isnumeric())
number = "4.22"  
print(number.isnumeric()) #will return false because of the dot. or any other special character. only accepts whole numbers